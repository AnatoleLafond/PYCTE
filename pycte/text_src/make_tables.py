"""Writes floatText_tables.h, the tables of powers of 5 of floatText.c (Ryu, U. Adams, PLDI 2018: the 'full table' of
d2s with DOUBLE_POW5_BITCOUNT = DOUBLE_POW5_INV_BITCOUNT = 125), computed exactly with Python integers.

    python make_tables.py      (in this folder; the header is kept in the sources, this script only remakes it)

POW5[i] = 5^i shifted to 125 significant bits (i = 0 .. 325, rounded down), POW5_INV[i] = floor(2^(len(5^i) - 1 + 125) /
5^i) + 1 (i = 0 .. 341), each as {low 64 bits, high 64 bits}."""
from pathlib import Path

POW5_BITCOUNT = 125
POW5_INV_BITCOUNT = 125
POW5_TABLE_SIZE = 326
POW5_INV_TABLE_SIZE = 342
MASK = (1 << 64) - 1


def pow5(i):
    value = 5 ** i
    shift = value.bit_length() - POW5_BITCOUNT
    return value >> shift if shift >= 0 else value << -shift


def pow5Inv(i):
    value = 5 ** i
    j = value.bit_length() - 1 + POW5_INV_BITCOUNT
    return (1 << j) // value + 1


def table(name, size, entry):
    rows = []
    for i in range(size):
        v = entry(i)
        assert v < (1 << 128)
        rows.append(f"  {{ {v & MASK}u, {v >> 64}u }},")
    return f"static const uint64_t {name}[{size}][2] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    text = ("/* Generated by make_tables.py (exact integer arithmetic): powers of 5 for floatText.c, Ryu 'full table'\n"
            "   layout {low 64 bits, high 64 bits}. Do not edit. */\n"
            f"#define POW5_BITCOUNT {POW5_BITCOUNT}\n#define POW5_INV_BITCOUNT {POW5_INV_BITCOUNT}\n"
            f"#define POW5_TABLE_SIZE {POW5_TABLE_SIZE}\n#define POW5_INV_TABLE_SIZE {POW5_INV_TABLE_SIZE}\n\n"
            + table("POW5_INV_SPLIT", POW5_INV_TABLE_SIZE, pow5Inv) + "\n"
            + table("POW5_SPLIT", POW5_TABLE_SIZE, pow5))
    Path(__file__).with_name("floatText_tables.h").write_text(text, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
